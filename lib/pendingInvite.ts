import type { KeyValueStorage } from './chunkedStorage';

/**
 * A "pending invite" remembers which bill (or group) a signed-out invitee was trying to open,
 * so we can send them back to it after sign-in. It is one-shot (taking it removes it)
 * and expires after a TTL so a shared device doesn't resume someone else's invite days later.
 *
 * Groups (docs/specs/2026-11-26-groups-mvp.md, T9): a group invite is stored under the same key as
 * `g-<code>`, so the root layout's resume effect (`postSignInRoute(takePendingInvite(...))`) needs no
 * change. There is one pending invite at a time; the newest one wins, whichever kind it is.
 */

export const PENDING_INVITE_KEY = 'splitit.pendingInvite';
export const PENDING_INVITE_TTL_MS = 24 * 60 * 60 * 1000;

const INVITE_CODE_RE = /^[A-Za-z0-9_-]{10,64}$/;
/** groups.join_code: 20 lowercase hex, generated by the database (T2). */
const GROUP_CODE_RE = /^[0-9a-f]{20}$/;

/** How a group invite is told apart from a bill code in storage. */
export const GROUP_INVITE_PREFIX = 'g-';

/**
 * Returns the trimmed code if it is a well-formed bill invite code, else null. Case is preserved.
 * A value starting with the group prefix (`g-`, any case) is refused: bill codes are 20 hex in the
 * database (`bills_join_code_format`), so no real one starts with it, and refusing it means a group
 * invite can never be read as a bill code or the other way round.
 */
export function normalizeInviteCode(raw: unknown): string | null {
  if (typeof raw !== 'string') return null;
  const code = raw.trim();
  if (code.toLowerCase().startsWith(GROUP_INVITE_PREFIX)) return null;
  return INVITE_CODE_RE.test(code) ? code : null;
}

/**
 * Returns the trimmed, lowercased code if it is a well-formed group join code (20 hex), else null.
 * Lowercasing is safe because the database only issues lowercase hex.
 */
export function normalizeGroupCode(raw: unknown): string | null {
  if (typeof raw !== 'string') return null;
  const code = raw.trim().toLowerCase();
  return GROUP_CODE_RE.test(code) ? code : null;
}

/** A stored value: a bill code, or `g-` + a group code. Anything else is null. */
function normalizeStoredCode(raw: unknown): string | null {
  if (typeof raw !== 'string') return null;
  if (raw.startsWith(GROUP_INVITE_PREFIX)) {
    const group = raw.slice(GROUP_INVITE_PREFIX.length);
    // Exact match only: the stored value was written by savePendingGroupInvite, already normalized.
    return GROUP_CODE_RE.test(group) ? raw : null;
  }
  return normalizeInviteCode(raw);
}

/** Stores `{ code, savedAt }`, replacing any older invite. Invalid codes are ignored. */
export async function savePendingInvite(storage: KeyValueStorage, code: string, now: number): Promise<void> {
  const valid = normalizeInviteCode(code);
  if (valid === null) return;
  await storage.setItem(PENDING_INVITE_KEY, JSON.stringify({ code: valid, savedAt: now }));
}

/**
 * Stores a group invite as `{ code: 'g-<code>', savedAt }`, replacing any older invite (bill or
 * group). Invalid codes are ignored and leave an older invite in place.
 */
export async function savePendingGroupInvite(storage: KeyValueStorage, code: string, now: number): Promise<void> {
  const valid = normalizeGroupCode(code);
  if (valid === null) return;
  await storage.setItem(PENDING_INVITE_KEY, JSON.stringify({ code: `${GROUP_INVITE_PREFIX}${valid}`, savedAt: now }));
}

/**
 * Returns the pending invite (a bill code, or `g-<code>` for a group) and removes it. Returns null (and removes the entry)
 * if it is expired, corrupt, or no longer valid. Never throws.
 */
export async function takePendingInvite(
  storage: KeyValueStorage,
  now: number,
  ttlMs: number = PENDING_INVITE_TTL_MS,
): Promise<string | null> {
  let raw: string | null;
  try {
    raw = await storage.getItem(PENDING_INVITE_KEY);
  } catch {
    return null;
  }
  if (raw === null) return null;

  await clearPendingInvite(storage);
  return parseStoredInvite(raw, now, ttlMs);
}

/** Removes any pending invite. Never throws. */
export async function clearPendingInvite(storage: KeyValueStorage): Promise<void> {
  try {
    await storage.removeItem(PENDING_INVITE_KEY);
  } catch {
    // Best effort: a stale entry still expires via the TTL.
  }
}

/**
 * The only places sign-in can send you: home, a validated bill invite (`/b/<code>`) or a validated
 * group invite (`g-<code>` → `/g/<code>`). No free-form return URLs; a malformed value is `/`.
 */
export function postSignInRoute(code: string | null): '/' | `/b/${string}` | `/g/${string}` {
  if (typeof code === 'string' && code.startsWith(GROUP_INVITE_PREFIX)) {
    const group = code.slice(GROUP_INVITE_PREFIX.length);
    return GROUP_CODE_RE.test(group) ? `/g/${group}` : '/';
  }
  const valid = normalizeInviteCode(code);
  return valid === null ? '/' : `/b/${valid}`;
}

function parseStoredInvite(raw: string, now: number, ttlMs: number): string | null {
  let parsed: unknown;
  try {
    parsed = JSON.parse(raw);
  } catch {
    return null;
  }
  if (typeof parsed !== 'object' || parsed === null) return null;
  const { code, savedAt } = parsed as { code?: unknown; savedAt?: unknown };
  if (typeof savedAt !== 'number' || !Number.isFinite(savedAt)) return null;
  // Expired, or saved "in the future" (clock change or tampering): drop it.
  if (savedAt > now || now - savedAt >= ttlMs) return null;
  return normalizeStoredCode(code);
}
